// Экран загрузки в стиле Вуали со списком шагов.
//
// Смысл не в красоте, а в наблюдаемости. Плата после прошивки может молча уйти в
// перезапуск, и снаружи это выглядит как «мигнула подсветка и погасла» — понять, на чём
// именно встало, нечем: монитор порта в этот момент обычно не подключён.
//
// Поэтому каждый шаг запуска пишется НА ЭКРАН по мере прохождения. Если плата
// перезапустится, последняя строка укажет виновника; если зависнет — тоже.
#pragma once

#include <stdint.h>

namespace boot {

/** Состояние шага. Цвет строки на экране зависит от него. */
enum Status : uint8_t {
    RUNNING,   // идёт
    OK,        // прошло
    WARN,      // не получилось, но жить можно
    FAIL,      // не получилось, дальше нельзя
};

/**
 * Поднять экран и показать заставку.
 *
 * Вызывается ПЕРВЫМ делом, до всего остального: пока экран не работает, никакая
 * диагностика не видна, и любая ошибка ниже превращается в чёрный прямоугольник.
 */
void begin();

/** Начать шаг: строка появляется серой с точкой. */
void step(const char* name);

/** Завершить текущий шаг. detail — короткое пояснение справа, можно nullptr. */
void done(Status st, const char* detail = nullptr);

/** Убрать экран загрузки и отдать экран приложению. */
void finish();

/** Показать неустранимую ошибку и остаться на экране: пусть человек видит причину,
 *  а не гадает по погасшей подсветке. */
void fatal(const char* what);

}  // namespace boot
