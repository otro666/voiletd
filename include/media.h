// Фотографии и стикеры.
//
// Экран 320×240, а приходящие с телефона снимки — это мегапиксели. Поэтому картинка
// никогда не разворачивается целиком: JPEG раскодируется блоками по 16×16 сразу в нужный
// масштаб и выводится на экран по мере разбора. Полный кадр 1080×1080 занял бы 2,2 МБ, и
// хотя PSRAM это выдержит, разбор занял бы секунды и оставил бы устройство без памяти
// под всё остальное.
#pragma once

#include <stdint.h>
#include <stddef.h>

namespace media {

constexpr int kScreenW = 320;
constexpr int kScreenH = 240;

// ── что умеем показывать ───────────────────────────────────────────────────────────────
//
// Телефонная версия шлёт стикеры файлами с тегом STICKER, и это, как правило, анимация в
// формате WebP. Раскодировать её на ESP32 нечем.
//
// Решение — как со звуком: договориться о форме, а не пытаться повторить чужой кодек.
// При отправке НА T-Deck телефон отдаёт стикер отдельным кадром в JPEG, а не исходником.
// Это требует правки на телефонной стороне, зато не требует WebP на плате.
enum ImageFormat : uint8_t {
    IMG_JPEG = 1,     // фотографии и статичные стикеры
    IMG_RGB565 = 2,   // готовый к выводу, для обложек на карте
    IMG_UNSUPPORTED = 0,
};

ImageFormat detect(const uint8_t* data, size_t len);

/**
 * Подобрать коэффициент уменьшения при разборе.
 *
 * Декодер JPEG умеет отдавать картинку сразу в 1/2, 1/4 или 1/8 размера почти бесплатно —
 * это свойство самого формата. Выбираем наибольшее уменьшение, при котором картинка ещё
 * не мельче экрана: так и памяти нужно меньше, и разбор быстрее.
 */
uint8_t pickScale(int srcW, int srcH, int dstW = kScreenW, int dstH = kScreenH);

/** Куда поместить картинку на экране с сохранением пропорций. */
struct Fit { int x, y, w, h; };
Fit fitCenter(int srcW, int srcH, int dstW = kScreenW, int dstH = kScreenH);

// ── обложки ────────────────────────────────────────────────────────────────────────────
//
// Обложка готовится ОДИН раз — когда файл появился, — и кладётся на карту рядом. Дальше
// показ списка это чтение готовой картинки, без разбора исходника. Ровно та же схема, к
// которой пришли в телефонной версии, и по той же причине: разбор при показе не успевает,
// и человек видит пустые плашки.
constexpr int kThumbSide = 96;

/** Имя файла обложки по идентификатору сообщения. */
void thumbPath(const char* fileId, char* out, size_t outLen);

}  // namespace media
