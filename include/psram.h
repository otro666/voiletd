// Внешняя память платы (PSRAM) — восемь мегабайт, которые до сих пор простаивали.
//
// Зачем это понадобилось. Внутренней памяти на плате около полумегабайта, и её съедали
// буферы модулей и защищённые соединения: каждое просит под сорок килобайт мелкими
// кусками, а мелкие куски система по умолчанию берёт ИЗ ВНУТРЕННЕЙ. Из-за этого рельсы
// не поднимались — Nostr и трекеры показывали нули, — при том что рядом лежало восемь
// свободных мегабайт.
//
// Два действия закрывают вопрос:
//   1. порог: всё, что крупнее нескольких килобайт, система сама начинает брать снаружи;
//   2. явное размещение: постоянные буфера модулей просим снаружи прямым вызовом.
//
// Чего сюда класть НЕЛЬЗЯ: буферы, в которые пишет оборудование напрямую (звуковая шина,
// шина экрана). Им нужна внутренняя память — это ограничение железа, а не выбор.
#pragma once

#include <stddef.h>
#include <stdint.h>

namespace psram {

/**
 * Включить внешнюю память для крупных выделений и рассказать в журнал, что получилось.
 *
 * Вызывать ОДИН раз при запуске, до подъёма сети и рельс: смысл в том, чтобы их
 * выделения уже попали наружу.
 */
void begin();

/** Есть ли внешняя память вообще (на плате без неё всё продолжает работать). */
bool available();

/**
 * Выделить буфер во внешней памяти.
 *
 * Если её нет или она кончилась — берём внутреннюю: отказ выделения означал бы, что
 * модуль не работает вовсе, а это хуже, чем работать чуть теснее. Память не
 * освобождается никогда — она выделяется один раз при запуске и живёт до выключения.
 */
void* alloc(size_t bytes);

/** Свободно во внешней и во внутренней памяти, байт — для экрана состояния и журнала. */
uint32_t freeExternal();
uint32_t freeInternal();

}  // namespace psram
