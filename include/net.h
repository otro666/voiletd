// Связь по сети.
//
// Три слоя, каждый работает поверх предыдущего:
//
//   1. Локальная сеть — рассылка объявления о себе. Находит собеседника в той же сети
//      БЕЗ интернета вообще, без посредников и без внешних адресов. Самый ценный слой:
//      он и даёт связь с телефоном дома.
//   2. Обмен по UDP — сами сообщения. Формат провода общий с телефоном.
//   3. Внешний адрес — нужен, только когда собеседники в разных сетях.
//
// Плюс МОСТ: если хоть один собеседник виден в сети, плата пересылает через него запросы
// знакомства от тех, кто доступен только по радио. Так устройство в поле знакомится с
// устройством в интернете, хотя между ними нет прямого пути.
#pragma once

#include <stdint.h>
#include <stddef.h>

namespace net {

// ── параметры, общие с телефонной версией ──────────────────────────────────────────────
//
// Менять нельзя: по ним плата и телефон находят друг друга. Взяты из VoileLan.kt.
constexpr const char* kLanGroup = "239.255.77.77";
constexpr uint16_t    kLanPort  = 47771;
constexpr uint32_t    kAnnounceMs = 5000;

/** Длина имени узла — та же, что в телефонной версии. */
constexpr size_t kIdLen = 20;

/** Поднять сеть. Вызывается после подключения к Wi-Fi. */
bool begin();

/** Работает ли сетевая часть. */
bool ready();

/** Подать сеть: приём пакетов, рассылка объявлений, поддержание связей.
 *  Зовётся из главного цикла — своего потока не заводим, чтобы не бороться за память. */
void pump();

/** Наш порт для обмена. */
uint16_t localPort();

/** Наше имя узла — двадцать байт, выведенных из долговременного ключа. */
const uint8_t* myId();

// ── внешний адрес ──────────────────────────────────────────────────────────────────────

/** Спросить у публичного сервера, как нас видно снаружи. Нужно, только когда собеседник
 *  в другой сети. Результат кладётся во внутреннее состояние. */
void refreshExternalAddress();

/** Внешний адрес в виде «1.2.3.4:5678» или пусто, если ещё не известен. */
const char* externalAddress();

// ── соседи в локальной сети ────────────────────────────────────────────────────────────

struct Neighbour {
    uint8_t  id[kIdLen];
    uint32_t ip;          // сетевой порядок
    uint16_t port;
    uint32_t lastSeenMs;
};

size_t neighbourCount();
const Neighbour* neighbourAt(size_t i);

// ── отправка ───────────────────────────────────────────────────────────────────────────

/** Отправить готовый кадр собеседнику по его имени узла. false — путь неизвестен. */
bool sendTo(const uint8_t id[kIdLen], const uint8_t* data, size_t len);

/** Что делать с принятым кадром. Ставится ядром при запуске. */
using OnFrame = void (*)(const uint8_t id[kIdLen], const uint8_t* data, size_t len);
void setOnFrame(OnFrame cb);

// ── мост радио ↔ интернет ──────────────────────────────────────────────────────────────

/**
 * Передать запрос знакомства из эфира в сеть.
 *
 * Устройство в поле слышно только по радио и не имеет выхода в интернет. Но если у нас
 * есть собеседник, видимый в сети, мы можем передать его запрос дальше — и знакомство
 * состоится, хотя прямого пути между ними нет.
 *
 * Это и есть смысл моста: плата с двумя способами связи соединяет тех, у кого способ
 * только один.
 */
bool bridgeToInternet(const uint8_t meetAddr[4], const uint8_t* payload, size_t len);

/** Обратное направление: пришедшее из сети объявление знакомства уходит в эфир. */
void setBridgeToRadio(void (*cb)(const uint8_t meetAddr[4], const uint8_t*, size_t));

/** Есть ли сейчас через кого мостить: хоть один собеседник виден в сети. */
bool bridgeAvailable();

}  // namespace net
