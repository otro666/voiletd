// Веб-сокет поверх защищённого соединения.
//
// Нужен обеим рельсам знакомства: телефонная версия ходит к брокерам именно так, а Nostr
// иначе и не умеет — у него нет варианта с обычным подключением вовсе.
//
// Своя реализация, а не библиотека: готовые тянут за собой изрядно лишнего, а нам нужен
// узкий срез — рукопожатие, отправка текстового кадра, приём, отклик на проверку связи.
#pragma once

#include <stdint.h>
#include <stddef.h>

class WiFiClientSecure;

namespace ws {

/** Состояние соединения. */
enum State : uint8_t {
    CLOSED = 0,
    CONNECTING,   // идёт рукопожатие
    OPEN,
};

struct Conn {
    WiFiClientSecure* cli = nullptr;
    State    state = CLOSED;
    uint32_t lastPing = 0;
    /** Признак поддиалога — по нему сверяем ответ сервера. Случайный на каждое
     *  соединение, иначе ответ можно было бы подделать заранее. */
    char     key[32] = {};
};

/**
 * Начать соединение. Возвращает false сразу, если не удалось даже подключиться.
 *
 * Рукопожатие делается тут же: оно короткое, а разносить его по кругам главного цикла
 * значило бы усложнить всё ради выигрыша в доли секунды. Вызывать из отдельного потока.
 */
bool open(Conn& c, WiFiClientSecure& cli, const char* host, uint16_t port,
          const char* path, const char* protocol);

/** Отправить текстовый кадр. */
bool sendText(Conn& c, const char* text, size_t len);

/** Отправить двоичный кадр — для брокера, который говорит своим языком поверх сокета. */
bool sendBinary(Conn& c, const uint8_t* data, size_t len);

/**
 * Принять кадр. Возвращает длину или 0, если целого кадра пока нет.
 *
 * isBinaryOut говорит, каким он пришёл: текстовым или двоичным. Проверку связи и закрытие
 * обрабатываем внутри и наверх не отдаём — вызывающему они не нужны.
 */
size_t receive(Conn& c, uint8_t* out, size_t outCap, bool* isBinaryOut);

/** Поддержать связь: отправить проверку, если давно молчали. */
void keepAlive(Conn& c);

void close(Conn& c);

}  // namespace ws
