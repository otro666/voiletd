// Цветные эмодзи.
//
// Настоящие цветные картинки, а не фигуры из линий: каждый нарисован заранее и хранится
// готовыми точками. Семнадцать штук — самые ходовые — занимают 28 КБ при 16 МБ памяти,
// то есть меньше двух десятых процента.
//
// Символ уходит собеседнику обычным кодом Unicode, поэтому на телефоне он выглядит
// привычно, а на плате рисуется своей картинкой. Переписка полностью совместима.
#pragma once

#include <stdint.h>
#include <stddef.h>

namespace emoji {

/** Сторона картинки в точках. */
constexpr int kSize = 32;   // крупнее прежних 28: сглаживание должно быть видно

struct Item {
    const char*     utf8;   // что уходит собеседнику
    const char*     name;   // подпись в панели выбора
    const uint16_t* pix;    // точки, готовые для экрана
    const uint8_t*  mask;   // прозрачность: по биту на точку
};

extern const Item kSet[];
extern const size_t kCount;

/**
 * Нарисовать эмодзи в точке (x, y) на подложке цвета bg.
 *
 * Подложка нужна для СГЛАЖИВАНИЯ: экран не читается обратно, и полупрозрачный край
 * картинки можно смешать только с известным цветом. Все места, где стоят эмодзи, —
 * пузырь, строка ввода, панель — рисуются на сплошном цвете, так что подложка всегда
 * известна вызывающему.
 *
 * Откуда берётся картинка: сначала ищем НАСТОЯЩУЮ на карте — /vual/emoji/1F4A9.png
 * и так далее. Настоящие наборы (Twemoji, OpenMoji, Noto) распространяются свободно,
 * весят пустяк и выглядят как везде; хранить их в прошивке значило бы раздувать её и
 * намертво привязываться к одному набору. Нет картинки — рисуем встроенный рисунок,
 * смягчая его край о подложку.
 */
void draw(size_t index, int x, int y, uint16_t bg);

/** То же, но в уменьшенном размере (для строки ввода): картинка прореживается до
 *  size×size точек. Без этого эмодзи в поле рисовался шрифтом — а в шрифте его нет,
 *  и вместо смайлика вставал квадрат-заглушка. */
void drawScaled(size_t index, int x, int y, int size, uint16_t bg);

/** Проверить, есть ли на карте набор картинок. Вызывается при запуске. */
void scanCard();

/** Сколько эмодзи нашлось на карте. Ноль — рисуем встроенными. */
size_t cardCount();

/** Узнать эмодзи в начале строки. Возвращает длину в байтах или 0.
 *  Нужно при показе полученного текста: символы приходят вперемешку с буквами. */
size_t match(const char* text, size_t& indexOut);

/** Панель выбора: сетка эмодзи внизу экрана. Возвращает высоту панели. */
int drawPicker(int y, size_t selected);

/** Какой эмодзи под пальцем в панели. -1 — мимо. */
int pickerHit(int panelY, int16_t x, int16_t y);

}  // namespace emoji
