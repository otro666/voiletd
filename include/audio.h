// Звук: голосовые сообщения и рация.
//
// СОВМЕСТИМОСТЬ С ТЕЛЕФОНОМ решается без AAC, и это принципиально: аппаратного кодера AAC
// у ESP32-S3 нет, а программный на 240 МГц в реальном времени не потянуть.
//
// В телефонной версии (VoileCall.kt) звонок допускает СМЕШАННЫЙ режим: кадр вида AUDIO
// несёт PCM, кадр AUDIO_AAC — сжатый, и одна сторона может слать одно, другая другое.
// Значит T-Deck шлёт PCM и остаётся понятным телефону без единой правки на той стороне.
//
// Внутри же и на LoRa используется ADPCM: вчетверо меньше при том же качестве речи и
// вычислениях, которые ESP32 тянет с огромным запасом.
#pragma once

#include <stdint.h>
#include <stddef.h>

namespace audio {

// Частота дискретизации совпадает с телефонной для рации. 16 кГц — разборчивая речь при
// вдвое меньшем потоке, чем 24 кГц.
constexpr int kSampleRate = 16000;
constexpr int kFrameSamples = 320;          // 20 мс — привычный размер кадра для речи

// ── ADPCM (IMA) ────────────────────────────────────────────────────────────────────────
//
// Сжатие 4:1: каждый отсчёт 16 бит превращается в 4 бита. Без таблиц частот и
// преобразований — только сложение и сдвиги, поэтому кодирование почти ничего не стоит.
//
// Для LoRa это единственный вариант: 20 мс речи в PCM — это 640 байт, в ADPCM — 160,
// и только второе влезает в пакет.

struct AdpcmState {
    int16_t predictor = 0;
    int8_t  index = 0;
};

/** Сжать блок отсчётов. Возвращает число записанных байт (samples/2). */
size_t adpcmEncode(AdpcmState& st, const int16_t* samples, size_t count, uint8_t* out);

/** Развернуть обратно. Возвращает число восстановленных отсчётов (bytes*2). */
size_t adpcmDecode(AdpcmState& st, const uint8_t* in, size_t bytes, int16_t* out);

// ── формат голосового сообщения ────────────────────────────────────────────────────────
//
// Голосовое уходит файлом, как в телефонной версии (тег VOICE). Внутри — заголовок и
// поток ADPCM. Телефон такой файл не поймёт напрямую, поэтому при отправке ПО WI-FI
// разворачиваем в WAV: это understands любой проигрыватель, и телефонная версия покажет
// его штатно. По LoRa шлём ADPCM как есть — там каждый байт на счету.

struct VoiceHeader {
    char     magic[4];      // "VUAV"
    uint8_t  codec;         // 1 = ADPCM, 2 = PCM
    uint8_t  reserved;
    uint16_t sampleRate;
    uint32_t samples;       // всего отсчётов
};

/** Записать заголовок WAV перед потоком PCM — для совместимости с телефоном. */
size_t writeWavHeader(uint8_t* out, uint32_t pcmBytes, int sampleRate);

// ── рация ──────────────────────────────────────────────────────────────────────────────
//
// Непрерывный поток, а не файл. Идёт быстрым путём (без гарантий доставки): потерянный
// кадр речи проще пропустить, чем ждать переспроса — переспрос придёт, когда фраза уже
// не нужна.
//
// По LoRa рация невозможна физически: 20 мс речи это 160 байт ADPCM, то есть 8 кбит/с,
// а канал даёт от 300 бит/с до 5,5 кбит/с. Поэтому рация работает ТОЛЬКО по Wi-Fi, и это
// не ограничение реализации, а арифметика.
constexpr int kPttBitrateBps = kSampleRate * 4;      // ADPCM: 4 бита на отсчёт

/** Влезает ли рация в канал с такой пропускной способностью. */
constexpr bool pttFitsIn(int channelBps) { return channelBps >= kPttBitrateBps * 5 / 4; }


// ── запись и воспроизведение на плате ──────────────────────────────────────────────────
//
// Голосовое записывается сразу СЖАТЫМ на карту: держать сырой звук в памяти нельзя —
// минута речи это почти два мегабайта, а свободной памяти куда меньше.

namespace device {

/** Поднять звуковую шину. false — микрофон не отозвался. */
bool begin();

/** Начать запись в файл. Возвращает false, если карта недоступна. */
bool startRecording(const char* path);

/** Подать накопленное с микрофона в файл. Зовётся из главного цикла. */
void pumpRecording();

/** Закончить запись. Возвращает длительность в миллисекундах. */
uint32_t stopRecording();

bool isRecording();

/** Проиграть записанное. */
bool play(const char* path);
void pumpPlayback();
void stopPlayback();
bool isPlaying();

}  // namespace device

}  // namespace audio

