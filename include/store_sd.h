// Хранение на карте памяти.
//
// Всё, что человек ввёл руками, обязано пережить перепрошивку: личность, сети с паролями,
// переписка. Иначе каждая новая сборка означает заново вводить имя, пароль от сети и
// терять всю историю — а прошивка на этом этапе меняется по нескольку раз в день.
//
// Формат намеренно простой: отдельные файлы, каждый со своим назначением. Одна общая база
// была бы аккуратнее, но при сбое питания посреди записи теряла бы всё сразу, а так —
// только тот файл, который писался.
#pragma once

#include <stdint.h>
#include <stddef.h>

namespace store {

/** Подготовить папки на карте. false — карты нет, всё останется только в памяти. */
bool begin();
bool ready();

// ── личность ───────────────────────────────────────────────────────────────────────────

/** Сохранить имя и ключевую пару. Ключ — это и есть личность: потеряется он, и все
 *  знакомства придётся заводить заново. */
bool saveIdentity(const char* name, const uint8_t* privKey, size_t privLen,
                  const uint8_t* pubKey, size_t pubLen);

bool loadIdentity(char* name, size_t nameCap,
                  uint8_t* privKey, size_t privLen,
                  uint8_t* pubKey, size_t pubLen);

// ── сети ───────────────────────────────────────────────────────────────────────────────

/** Запомнить сеть с паролем. Пароли лежат на карте открыто — и это надо понимать:
 *  вынув карту, их прочтут. Шифровать их было бы нечем: ключ пришлось бы хранить рядом. */
bool saveWifi(const char* ssid, const char* pass);

/** Найти пароль к сети по имени. */
bool findWifi(const char* ssid, char* pass, size_t passCap);

/** Имя последней успешной сети — к ней и подключаемся при запуске. */
bool lastWifi(char* ssid, size_t ssidCap, char* pass, size_t passCap);

// ── переписка ──────────────────────────────────────────────────────────────────────────

/** Дописать сообщение в историю собеседника. */
bool appendMessage(const char* peer, bool mine, uint32_t ts, const char* text);

/** Прочитать последние сообщения. Возвращает, сколько прочитано. */
size_t loadMessages(const char* peer, size_t maxCount,
                    void (*cb)(bool mine, uint32_t ts, const char* text));

/** Путь для медиа собеседника — туда складываются снимки и голосовые. */
const char* mediaPath(const char* peer, const char* fileName);

// ── журнал ─────────────────────────────────────────────────────────────────────────────

/** Записать строку в журнал на карте. Нужен, чтобы разбирать то, что случается без
 *  подключённого монитора порта, — а это большинство случаев. */
void log(const char* tag, const char* text);

/** Сколько всего записано. По этому числу видно, растёт ли журнал. */
uint32_t logSize();

/**
 * Прочитать ПОСЛЕДНИЕ строки журнала для показа на экране.
 *
 * Именно последние: разбираются всегда свежие события, а держать в памяти весь журнал
 * нельзя — он может быть в мегабайты, которых на плате нет.
 *
 * Возвращает, сколько строк прочитано. Строки складываются в переданный буфер.
 */
size_t logTail(char* buf, size_t bufCap, const char** lines, size_t maxLines);

/**
 * Прочитать страницу журнала с конца: page 0 — самые свежие, дальше вглубь.
 *
 * Постранично, а не целиком: журнал бывает в мегабайты, и держать его в памяти нечем.
 * Так пролистывается ВЕСЬ файл, а не только хвост — прежде дальше сотни строк уйти
 * было нельзя.
 *
 * Возвращает число прочитанных строк; hasMore говорит, есть ли что-то ещё глубже.
 */
size_t logPage(size_t page, size_t perPage, char* buf, size_t bufCap,
               const char** lines, bool* hasMore);

/** Очистить журнал. */
bool logClear();

}  // namespace store
