// Обфускация пакетов — точное повторение слоя из телефонной версии.
//
// Каждый пакет одевается в неприметный вид и шифруется гаммой, а ключ и внешний облик
// меняются каждые двадцать минут. Смысл в том, что даже разобравшись с текущим обликом,
// цензор получает правило, которое протухнет: сигнатура становится движущейся целью.
//
// Формат обязан совпадать с телефонным ДО БАЙТА, иначе плата и телефон не поймут друг
// друга вовсе. Все значения — метки, длина эпохи, порядок действий — взяты оттуда как есть.
#pragma once

#include <stdint.h>
#include <stddef.h>

namespace cloak {

/** Длина эпохи. Стороны считают её независимо и договариваться не нужно. */
constexpr uint64_t kEpochMs = 20ULL * 60 * 1000;

/** Номер текущей эпохи. */
uint64_t epoch(uint64_t nowMs);

/** Базовый ключ для рассылки в локальной сети и первого знакомства. */
const uint8_t* discoveryKey();

/** Базовый ключ для обращения к конкретному узлу. */
void keyForNode(const uint8_t nodeId[20], uint8_t out[32]);

/**
 * Одеть пакет: зашифровать гаммой эпохи и придать неприметный вид.
 * Возвращает длину результата или 0, если не поместилось.
 */
size_t seal(const uint8_t baseKey[32], const uint8_t* payload, size_t len,
            uint8_t* out, size_t outCap);

/**
 * Раздеть обратно. Пробуем текущую эпоху и соседние: часы у сторон расходятся, и пакет
 * мог уйти в одной эпохе, а прийти в другой — без этого связь рвалась бы каждые
 * двадцать минут ровно на границе.
 */
size_t open(const uint8_t baseKey[32], const uint8_t* buf, size_t len,
            uint8_t* out, size_t outCap);

}  // namespace cloak
