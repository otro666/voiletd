// Интерфейс в стиле Вуали на экране 320×240.
//
// Переработан под привычный вид современного мессенджера: сообщения — пузырями с
// переносом слов, список собеседников — с кружками-аватарами и удалением, шрифты —
// сглаженные (VLW, см. fonts_vlw.h), цвета — насыщенные. Компоновка по-прежнему своя:
// 320×240 — это примерно четверть площади телефонного экрана, поэтому список чатов и
// переписка не помещаются одновременно, и экраны переключаются.
#pragma once

#include <stdint.h>
#include <stddef.h>

namespace ui {

// ── палитра ────────────────────────────────────────────────────────────────────────────
//
// Цвета задаются ЯВНЫМ преобразованием, а не просто числом.
//
// Обычное число библиотека понимает по-разному в зависимости от того, какой перегрузке
// оно достанется: как готовый цвет экрана или как обычную запись. Отсюда и брались цвета
// «мимо»: фон выходил то белым, то голубым вместо почти чёрного. Явное преобразование
// снимает вопрос — значение всегда трактуется одинаково.
inline uint16_t rgb(uint8_t r, uint8_t g, uint8_t b) {
    return uint16_t(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3));
}

// Цвета — В ТОЧНОСТИ телефонные (VualColors), чтобы устройства выглядели одним
// продуктом. Я пробовал «насытить» их по-своему — на этой матрице фон ушёл в
// грязно-серый, а шапка в защитно-зелёный. Телефонные значения проверены глазами на
// телефоне, и равняться надо на них, а не на вкус по памяти.
const uint16_t kBg          = rgb(0x0B, 0x07, 0x10);   // фон — почти чёрный с фиолетовым
const uint16_t kSurface     = rgb(0x16, 0x13, 0x1F);   // шапка, строка ввода, панели
const uint16_t kSurfaceHigh = rgb(0x1F, 0x1B, 0x2B);   // приподнятые плашки, чужие пузыри
const uint16_t kAccent      = rgb(0x6C, 0x4B, 0xFF);   // акцент: кнопки, свои пузыри
const uint16_t kAccentLight = rgb(0x8B, 0x7B, 0xFF);   // подсветки
const uint16_t kTextPrimary = rgb(0xFF, 0xFF, 0xFF);
const uint16_t kTextSecond  = rgb(0x9B, 0x9A, 0xA6);
const uint16_t kTextTertiary= rgb(0x57, 0x54, 0x6A);
const uint16_t kOnline      = rgb(0x6C, 0xCB, 0x5F);   // на связи
const uint16_t kWarning     = rgb(0xE0, 0xA3, 0x3E);
const uint16_t kDanger      = rgb(0xE5, 0x43, 0x2F);

/** Цвет кружка-аватара: выводится из имени, чтобы у каждого собеседника был свой и
 *  постоянный. Набор подобран сочным, но различимым на тёмном фоне. */
uint16_t avatarColor(const char* name);

// ── экраны ─────────────────────────────────────────────────────────────────────────────
enum Screen : uint8_t {
    SCR_CHATS,      // список собеседников
    SCR_CHAT,       // переписка
    SCR_MENU,       // главное меню: куда идти дальше
    SCR_IDENTITY,   // своё имя и ключ
    SCR_ADD,        // знакомство по сети
    SCR_ADD_RADIO,  // знакомство по радио
    SCR_LOG,        // просмотр журнала
    SCR_WIFI,       // выбор сети
    SCR_WIFI_PASS,  // ввод пароля к выбранной сети
    SCR_STATUS,     // состояние: радио, сеть, эфирное время, карта памяти
};

// ── состояние строки заголовка ─────────────────────────────────────────────────────────
struct Status {
    bool     linkUp;        // есть ли слышимые соседи
    int      neighbours;    // сколько узлов слышно
    int      rssi;          // уровень последнего принятого, дБм
    float    snr;           // отношение сигнал-шум, дБ
    uint8_t  battery;       // заряд, %
};

void begin();

/** Перерисовать целиком. Вызывается только при смене экрана: полная отрисовка на этом
 *  контроллере занимает заметное время, и делать её на каждый кадр нельзя. */
void draw(Screen s);

/** Обновить только строку состояния — дёшево, можно раз в секунду. */
void drawStatus(const Status& st);

/**
 * Пункты меню. Раньше их не было вовсе: после запуска человек видел список собеседников
 * и не понимал, как добавить контакт, куда подключиться и где посмотреть состояние.
 */
enum MenuItem : uint8_t {
    MENU_IDENTITY,  // кто я — имя и ключ
    MENU_CALIBRATE, // настроить сенсор
    MENU_ADD_NET,   // знакомство через интернет
    MENU_ADD_RADIO, // знакомство по радио
    MENU_LOG,       // журнал
    MENU_WIFI,      // подключиться к сети
    MENU_STATUS,    // состояние устройства
    MENU_BACK,      // назад к перепискам
    MENU_COUNT,
};

/**
 * Куда попал палец.
 *
 * Экран сенсорный, и человек ждёт, что нажимается всё видимое. Раньше касание работало
 * только на списке собеседников — остальное приходилось выбирать трекболом, о чём никто
 * не догадывался.
 */
enum Hit : uint8_t {
    HIT_NONE = 0,
    HIT_BURGER,      // значок меню в шапке
    HIT_BACK,        // стрелка назад
    HIT_LAYOUT,      // значок раскладки в строке ввода
    HIT_SEND,        // отправить
    HIT_EMOJI,       // значок смайликов в строке ввода
    HIT_MIC,         // запись голосового
    HIT_EMOJI_CELL,  // смайлик в панели; номер — в rowIndex
    HIT_ROW,         // строка списка; номер — в rowIndex
    HIT_DELETE,      // крестик удаления контакта; номер строки — в rowIndex
};

struct HitResult { Hit what; int rowIndex; };

/** Что находится в точке касания на текущем экране. */
HitResult hitTest(Screen s, int16_t x, int16_t y);

/** Отрисовать меню с выбранным пунктом. */
void drawMenu(MenuItem selected);

/** Экран знакомства: поле для кодового слова и подсказка. */
void drawAdd(const char* phrase, const char* status);

/** Знакомство ПО РАДИО — отдельно от сетевого.
 *
 *  Разное по сути: по сети собеседник может быть где угодно, по радио — только в пределах
 *  слышимости, и ждать его надо иначе. Сводить их в один экран значило бы путать. */
void drawAddRadio(const char* phrase, const char* status, int heard);

/** Просмотр журнала прямо на устройстве: вынимать карту ради него неудобно, а понять,
 *  что происходит, надо здесь и сейчас. */
void drawLog(const char* const* lines, size_t count, size_t from);

/**
 * Экран личности: своё имя и свой адрес.
 *
 * Без личности знакомиться не с чем — собеседник узнаёт устройство по ключу. Ключ
 * создаётся один раз при первом вводе имени и больше не меняется: пересоздание разорвало
 * бы все прежние знакомства.
 */
void drawIdentity(const char* name, const char* addr, bool haveKey);

/**
 * Настроить сенсор: показать уголки и вывести поправку.
 *
 * Сенсорная панель и матрица — разные устройства, их координаты совпадают лишь
 * приблизительно, и без поправки палец попадает мимо тем сильнее, чем дальше от центра.
 * Заполняет out восемью числами — их надо сохранить и применять при каждом запуске.
 */
void calibrateTouch(uint16_t out[8]);

/** Экран сети: список найденных, выбранная, состояние подключения. */
void drawWifi(const char* const* names, const int* levels, size_t count,
              size_t selected, const char* status);

/**
 * Ввод пароля к сети.
 *
 * Раньше подключение шло без пароля вовсе, и к закрытой сети — а такие почти все —
 * попасть было нельзя. Пароль показываем точками, но с возможностью подсмотреть: набирать
 * вслепую на клавиатуре такого размера мучительно.
 */
void drawWifiPass(const char* ssid, const char* pass, bool reveal, const char* status);

/** Экран состояния: всё, что стоит знать о железе и связи. */
void drawStatus2(const Status& st, const char* ip, bool radioOk, bool sdOk);

/** Добавить сообщение в текущую переписку. */
void addMessage(const char* text, bool mine, uint32_t ts, bool delivered);

/** Добавить ГОЛОСОВОЕ: пузырь с кнопкой проигрывания. path — файл на карте,
 *  seconds — длительность для подписи. Нажатие на пузырь проигрывает именно его. */
void addVoiceMessage(const char* path, int seconds, bool mine, bool delivered);

/** Путь к голосовому по номеру сообщения из hitTest; пусто — сообщение не голосовое. */
const char* voiceAt(int index);

/** Очистить ленту. Обязательно при открытии другой переписки: без этого сообщения
 *  разных собеседников перемешивались в одной ленте. */
void clearMessages();

/** Отметить последнее своё сообщение доставленным (пришло подтверждение) —
 *  у него появляется вторая галочка. */
void markDelivered();

/** Прокрутить ленту. Плюс — вверх, к старому; минус — вниз, к свежему.
 *  Смещение в точках; лента сама не даёт укатиться за края. */
void chatScroll(int deltaPx);

/** Прокрутить список собеседников на столько-то строк (плюс — вниз по списку).
 *  Нужна пальцу: трекбол листает выделением, а палец двигает само окно. */
void peersScroll(int deltaRows);

/** Строка ввода внизу экрана. cyrillic — какая раскладка сейчас активна. */
void setInput(const char* text, size_t caret, bool cyrillic);

/** Состояние Shift для значка раскладки: 0 — обычное, 1 — одна заглавная,
 *  2 — верхний регистр. Значок показывает его собственным регистром: ру → Ру → РУ. */
void setShiftMode(uint8_t mode);

/** Обновить значки связи в шапке: сеть, радио, рельса знакомства. */
void setLinkState(bool wifi, bool radio, bool rail);

/** Открыта ли панель смайликов. Разбор касаний зависит от этого: пока она открыта,
 *  нижняя часть экрана принадлежит ей, а не ленте. */
void setEmojiOpen(bool open);

/** Идёт запись голосового: показать полоску и оставшееся время. */
void setRecording(bool on, uint32_t elapsedMs);

/** Ход перекачки файла — узкая полоска над строкой ввода. percent 0…100;
 *  минус — скрыть. Без неё минутный приём голосового по радио выглядит как
 *  «ничего не происходит», и человек уходит с экрана. */
void setTransfer(int percent, bool incoming, bool voice);
bool emojiOpen();

/**
 * Взвод удаления контакта.
 *
 * Первое касание крестика только ВЗВОДИТ удаление: крестик краснеет, под именем
 * появляется «нажмите ещё раз». Второе касание того же крестика удаляет, любое другое —
 * отменяет. Одно случайное касание не должно стирать собеседника вместе с ключом:
 * восстановить его можно только новым знакомством.
 */
void armDelete(int row);     // -1 — снять взвод
int  armedDelete();          // какой ряд взведён; -1 — никакой

/**
 * Значок раскладки в строке ввода: «РУ» или «EN».
 *
 * Он же и КНОПКА: касание переключает раскладку. Это главный способ — видимый и
 * очевидный, в отличие от сочетания клавиш, о котором надо знать заранее.
 * Возвращает область для попадания пальцем.
 */
struct Rect { int16_t x, y, w, h; };
Rect layoutBadgeRect();

/** Список собеседников. unread — счётчики непрочитанного (можно nullptr): у строки с
 *  ненулевым счётчиком рисуется акцентный кружок с числом — как в любом мессенджере. */
void setPeers(const char* const* names, const bool* online, size_t count, size_t selected,
              const uint8_t* unread = nullptr);

}  // namespace ui
