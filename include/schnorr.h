// Подпись BIP340 — та, которой пользуется Nostr.
//
// В библиотеке её нет: есть только математика на кривой, а сама схема подписи другая.
// Пришлось выписать по стандарту.
//
// Отличий от привычной подписи два, и оба важны:
//
//   · открытый ключ хранится ТОЛЬКО как координата X, без указания знака. Из-за этого
//     при каждой операции ключ приводится к чётному варианту — иначе подпись не сойдётся;
//   · хеш считается не просто от сообщения, а с меткой назначения. Метка не даёт
//     перепутать подписи разных применений одной и той же схемы.
#pragma once

#include <stdint.h>
#include <stddef.h>

namespace schnorr {

/** Открытый ключ из закрытого. Отдаёт 32 байта — только координату X. */
bool publicKey(const uint8_t sk[32], uint8_t xOnly[32]);

/** Подписать 32-байтовый хеш. Подпись — 64 байта. */
bool sign(const uint8_t msg32[32], const uint8_t sk[32], uint8_t sig[64]);

}  // namespace schnorr
