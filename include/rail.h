// Рельса знакомства через MQTT.
//
// Через неё двое находят друг друга, когда прямого пути между ними нет: обе стороны
// приходят в «комнату», выведенную из общего кодового слова, и обмениваются адресами.
// Именно так знакомится телефонная версия, и без этой рельсы плата с телефоном
// встретиться не может — совпадения формулы мало, нужен общий способ прийти в комнату.
//
// Подключение ЗАЩИЩЁННОЕ. Открытое было бы проще, но тогда всякий на пути видел бы,
// в какую комнату мы пришли, — а имя комнаты выведено из кодового слова и выдаёт сам
// факт знакомства. Защищённое соединение это закрывает.
//
// Формат сообщений повторён с телефонной версии до буквы: тема «vual1/<комната>»,
// содержимое — тот же набор полей.
#pragma once

#include <stdint.h>
#include <stddef.h>

namespace rail {

/**
 * Все брокеры из телефонной версии — ВСЕ ШЕСТЬ, тот же список и тот же порядок.
 *
 * Держать их одновременно нужно потому, что доступность у каждого своя: один лежит,
 * второй режется у оператора, третий недоступен из конкретной страны. Собеседник придёт
 * к какому-то одному, и угадать, к какому именно, нечем — значит надо быть везде.
 */
constexpr size_t kMaxBrokers = 6;

/** Что пришло из комнаты. */
struct Incoming {
    char    kind;          // 'p' присутствие, 'o' предложение, 'a' ответ
    char    room[41];      // комната в шестнадцатеричном виде
    uint8_t peerId[20];    // кто прислал
    uint8_t offerId[20];   // к какому предложению относится
    bool    hasOffer;
    char    body[512];     // адрес и всё, что нужно для прямой связи
};

using OnMessage = void (*)(const Incoming&);

/** Поднять рельсу. Подключение идёт в фоне, ждать не нужно. */
bool begin(const uint8_t myPeerId[20]);

/** Подать рельсу: подключение, приём, поддержание связи. Из главного цикла. */
void pump();

/** Хоть один брокер на связи. */
bool connected();

/** Прийти в комнату и слушать её. */
void joinRoom(const char* roomHex);

/** Уйти из комнаты — например, когда знакомство состоялось. */
void leaveRoom(const char* roomHex);

/** Объявить о себе в комнате: «я здесь». */
void announce(const char* roomHex);

/** Отправить предложение связи с нашим адресом. */
void sendOffer(const char* roomHex, const uint8_t offerId[20], const char* body);

/** Ответить на чужое предложение. */
void sendAnswer(const char* roomHex, const uint8_t offerId[20], const char* body);

void setOnMessage(OnMessage cb);

/** Имена брокеров и их состояние — для экрана состояния. */
size_t brokerCount();
const char* brokerName(size_t i);
bool brokerOnline(size_t i);

}  // namespace rail
