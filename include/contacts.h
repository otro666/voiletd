// Контакты и знакомство.
//
// Знакомство по кодовому слову — тот же способ, что в телефонной версии: двое называют
// друг другу общую фразу любым путём, вводят её каждый у себя, и связь устанавливается
// сама. Ничего вводить вручную, сканировать или регистрировать не нужно.
//
// Почему именно так, а не обмен ключами по радио: в эфире слушают все, и объявление
// «я такой-то, вот мой ключ» выдаёт присутствие человека всякому с приёмником. Фраза же
// известна только двоим, и по ней выводится общий секрет, которым закрыто само знакомство.
#pragma once

#include <stdint.h>
#include <stddef.h>

#include "voile_crypto.h"

namespace contacts {

constexpr size_t kMaxContacts = 16;
constexpr size_t kNameLen = 24;

struct Contact {
    char     name[kNameLen];
    uint8_t  addr[4];                 // усечённый отпечаток — им адресуются кадры
    uint8_t  pubComp[voile::kPubComp];// долговременный ключ собеседника
    bool     used;
    bool     viaWifi;                 // отвечал по Wi-Fi
    bool     viaLora;                 // слышен по радио
    uint32_t lastSeenMs;
};

// ── адрес из ключа ─────────────────────────────────────────────────────────────────────

/**
 * Адрес узла — первые четыре байта хеша от его публичного ключа.
 *
 * Короткий адрес нужен, потому что полный ключ в 33 байта не поместить в заголовок кадра
 * при пределе пакета в 255 байт. Четырёх байт достаточно: совпадение у двух контактов из
 * шестнадцати практически исключено, а подделать адрес бессмысленно — расшифровать
 * сообщение всё равно нечем.
 */
void addrFromPub(const uint8_t pubComp[voile::kPubComp], uint8_t out[4]);

// ── знакомство по фразе ────────────────────────────────────────────────────────────────

/**
 * Вывести из кодовой фразы то, что нужно для знакомства.
 *
 * Из фразы получаются две вещи: адрес встречи, по которому стороны находят друг друга,
 * и ключ, которым закрыт сам обмен ключами. Растяжение намеренно долгое — фразы люди
 * придумывают короткие, и без растяжения перебор по словарю занял бы секунды.
 */
struct Rendezvous {
    uint8_t meetAddr[4];    // куда слать приглашение по РАДИО
    uint8_t wrapKey[32];    // чем закрыт обмен ключами
    uint8_t phoneRoom[20];  // комната присутствия для ТЕЛЕФОНА (SHA-1, 20 байт)
};

/**
 * Вывести всё нужное для знакомства — сразу для обеих сред.
 *
 * Одна и та же фраза даёт два разных адреса, и это не дублирование, а необходимость:
 * телефон ищет собеседника в «комнате» по своей формуле, сложившейся до появления платы
 * и менять которую нельзя без потери совместимости со всеми установленными версиями.
 * Радио же требует короткий адрес — в заголовок кадра при пределе 255 байт двадцать байт
 * не поместить.
 *
 * Поэтому из фразы выводятся оба: комната для телефона по ЕГО формуле, короткий адрес для
 * эфира по нашей. Человек вводит фразу один раз и находит обоих.
 */
void deriveRendezvous(const char* phrase, Rendezvous& out);

/** Нормализация фразы — в точности как в телефонной версии (Rooms.normSecret):
 *  обрезка по краям, нижний регистр, схлопывание пробелов. Расхождение здесь означало бы,
 *  что «Зелёный  Чайник» и «зелёный чайник» дают разные комнаты. */
size_t normalizePhrase(const char* in, char* out, size_t outLen);

/** Сколько раз прогоняем фразу через хеш. Компромисс: на 240 МГц это доли секунды,
 *  а перебор по словарю дорожает на четыре порядка. */
constexpr uint32_t kPhraseRounds = 20000;

// ── СВОЯ ЛИЧНОСТЬ ──────────────────────────────────────────────────────────────────────
//
// Долговременная пара ключей устройства и имя, под которым тебя видят собеседники.
// Одна и та же и для связи по сети, и по радио: собеседник узнаёт устройство по ключу,
// а не по способу связи, и знакомство, сделанное через интернет, работает потом в эфире.
//
// Ключ создаётся при первом запуске и хранится на карте. Пропадёт он — пропадут все
// знакомства: собеседники узнают именно его.

/** Своё имя. Пусто — личность ещё не заведена. */
const char* myName();

/** Свой долговременный публичный ключ. */
const uint8_t* myPub();

/** Свой адрес — то, что видят собеседники. */
void myAddr(uint8_t out[4]);

/** Задать имя и, если ключа ещё нет, создать его. Возвращает false, если не удалось
 *  создать ключ — без него ни знакомство, ни переписка невозможны. */
bool setMyName(const char* name);

/** Есть ли уже личность: имя задано и ключ создан. */
bool haveIdentity();

/** Доступ к полям личности для сохранения на карту.
 *
 *  Сама работа с картой лежит отдельно: этот модуль проверяется на компьютере, где ни
 *  карты, ни Arduino нет, и подтягивать их сюда значило бы сломать проверку. */
uint8_t* myPrivMutable();
uint8_t* myPubMutable();
char* myNameMutable();
void markKeysReady();

// ── хранилище ──────────────────────────────────────────────────────────────────────────

void begin();
size_t count();
Contact* at(size_t i);
Contact* byAddr(const uint8_t addr[4]);

/** Добавить или обновить. Возвращает nullptr, если места нет. */
Contact* upsert(const char* name, const uint8_t pubComp[voile::kPubComp]);

/** Удалить контакт по номеру, сдвинув остальных. Восстановить удалённого нечем —
 *  вместе с записью пропадает его ключ, и знакомиться придётся заново. Поэтому
 *  интерфейс спрашивает подтверждение, а не зовёт это по первому касанию. */
bool removeAt(size_t i);

/** Отметить, каким путём собеседник только что был слышен. */
void markSeen(const uint8_t addr[4], bool wifi, uint32_t nowMs);

/** Сохранить на карту и прочитать обратно. Контакты обязаны переживать выключение —
 *  иначе после разряда батареи придётся знакомиться заново. */
bool save();
bool load();

}  // namespace contacts
