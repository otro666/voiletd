// ── настройки радио ────────────────────────────────────────────────────────────────────
//
// Выбраны под городскую застройку, где главная беда — переотражения от стеклянных фасадов.
// Обоснование каждого значения:

// Несущая: 433 МГц проходит сквозь препятствия заметно лучше, чем 868. Менять её вниз
// смысла нет — синтезатор SX1262 ограничен снизу примерно 150 МГц, а выигрыш в 9 дБ
// съедается полуметровой антенной, которую на такое устройство не поставить.
#define LORA_FREQ_MHZ      433.5f

// ПОЧЕМУ НЕ УЗКАЯ ПОЛОСА И НЕ SF12. Прежний набор (31,25 кГц + SF12 + 4/8) давал на
// бумаге лучший бюджет линии, а на деле платы не слышали друг друга по двум причинам:
//
//  1. Узкая полоса требует суммарной точности частоты около ±18 ppm на 433 МГц
//     (~±7,8 кГц — четверть полосы). Разбег двух генераторов легко выходит за этот
//     допуск, и пакет не демодулируется ВООБЩЕ — тишина, неотличимая от поломки.
//  2. Один кадр занимал эфир до минуты. Плата, которая передаёт, не слушает
//     (радио полудуплексное) — обе платы почти всё время говорили и никогда не слышали.
//
// Поэтому здесь заведомо рабочий набор: полоса 125 кГц (допуск по частоте втрое мягче,
// ±31 кГц), SF9, кодирование 4/5. Кадр в 50 байт — доли секунды вместо четверти минуты.
// Дальность по-прежнему сотни метров в застройке и километры на открытом месте.
//
// Ужесточать — только СТУПЕНЯМИ и только после устойчивой связи на этих значениях:
// сначала 62,5 кГц, потом SF10–11, каждый шаг проверяя связь. На 31,25 кГц не
// возвращаться без уверенности в TCXO обеих плат.
#define LORA_BW_KHZ        125.0f
#define LORA_SF            9
#define LORA_CR            5

// +14 дБм (25 мВт). Намеренно НЕ максимум: до +15 дБм у SX1262 работает экономичный
// усилитель, рассчитанный на длительную работу. Выше включается мощный — вчетверо
// больший ток, ощутимый нагрев и куда меньший запас при рассогласовании антенны.
// Разница в бюджете линии 8 дБ, но надёжность и температура важнее.
#define LORA_POWER_DBM     14

// Ограничитель тока: с запасом над реальным потреблением, но достаточно низкий, чтобы
// сработать при рассогласовании раньше, чем перегреется усилитель.
#define LORA_CURRENT_MA    60

// Термокомпенсированный генератор модуля питается от вывода DIO3. На полосе 125 кГц
// допуск по частоте мягкий и даже обычный кварц прошёл бы, но TCXO на T-Deck есть, и
// пользоваться им правильно. Штатные примеры LilyGo работают с напряжением по
// умолчанию (1,6 В); 1,8 В тоже в допуске. Если radio.begin вернёт ошибку -706
// (генератор не завёлся) — попробуйте 1.6f.
#define LORA_TCXO_V        1.8f

// Стандартная преамбула: на 125 кГц пакет короткий, удлинять её незачем.
#define LORA_PREAMBLE      8

