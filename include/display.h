// Настройка экрана T-Deck.
//
// LovyanGFX вместо TFT_eSPI намеренно. TFT_eSPI настраивается флагами сборки: пропущенный
// или неверный флаг не вызывает ни ошибки компиляции, ни предупреждения — плата просто
// падает внутри инициализации, и найти виновника можно только перебором. Именно это и
// произошло: падение по нулевому адресу прямо в tft.init().
//
// Здесь вся настройка — обычный код: видно, какой блок шины, какие выводы, какая панель.
// Ошибку видит компилятор, а не человек по следу падения. Эту же библиотеку LilyGo
// применяет в своих примерах для T-Deck.
#pragma once

#define LGFX_USE_V1
#include <LovyanGFX.hpp>

#include "board.h"

class VualDisplay : public lgfx::LGFX_Device {
    lgfx::Panel_ST7789 _panel;
    lgfx::Bus_SPI      _bus;
    lgfx::Touch_GT911  _touch;

public:
    VualDisplay() {
        {   // ── шина ──
            auto cfg = _bus.config();
            // Тот же блок, что достанется радио: устройства делят выводы, а очередь между
            // ними обеспечивают линии выбора.
            cfg.spi_host   = SPI2_HOST;
            cfg.spi_mode   = 0;
            cfg.freq_write = 40000000;
            cfg.freq_read  = 16000000;
            cfg.spi_3wire  = false;
            cfg.use_lock   = true;          // обязательно: шину делят экран, карта и радио
            cfg.dma_channel = SPI_DMA_CH_AUTO;
            cfg.pin_sclk   = BOARD_SPI_SCK;
            cfg.pin_mosi   = BOARD_SPI_MOSI;
            cfg.pin_miso   = BOARD_SPI_MISO;
            cfg.pin_dc     = BOARD_TFT_DC;
            _bus.config(cfg);
            _panel.setBus(&_bus);
        }
        {   // ── панель ──
            auto cfg = _panel.config();
            cfg.pin_cs   = BOARD_TFT_CS;
            cfg.pin_rst  = -1;              // сброс заведён на общее питание платы
            cfg.pin_busy = -1;

            // Размеры даём в «портретной» ориентации самой матрицы; горизонтальный вид
            // получаем поворотом при запуске.
            cfg.panel_width      = 240;
            cfg.panel_height     = 320;
            cfg.offset_x         = 0;
            cfg.offset_y         = 0;
            cfg.offset_rotation  = 0;
            cfg.dummy_read_pixel = 8;
            cfg.dummy_read_bits  = 1;
            cfg.readable         = false;   // чтение из панели не используем
            // Инверсия ВКЛЮЧЕНА — этой матрице она нужна.
            //
            // В прошлый раз я снял её по ошибке: тёмная тема выходила светло-бирюзовой, но
            // виноваты были неверно пересчитанные цвета, а не инверсия. Сняв её, я получил
            // белый фон, чёрный текст и оливковое выделение — то есть точную инверсию
            // фиолетовой темы: 0x6C4BFF при инверсии даёт 0x93B400, оливковый.
            cfg.invert           = true;
            cfg.rgb_order        = false;
            cfg.dlen_16bit       = false;
            cfg.bus_shared       = true;    // шина общая — см. выше
            _panel.config(cfg);
        }
        {   // ── сенсор ──
            //
            // Берём ГОТОВЫЙ драйвер библиотеки вместо своего опроса регистров. Свой я
            // писал по документации и он не заработал — а этот уже знает и особенности
            // микросхемы, и порядок её пробуждения.
            auto cfg = _touch.config();
            cfg.i2c_port = 0;
            cfg.pin_sda  = BOARD_I2C_SDA;
            cfg.pin_scl  = BOARD_I2C_SCL;
            cfg.pin_int  = -1;            // прерывание не заведено, опрашиваем сами
            cfg.pin_rst  = -1;
            cfg.freq     = 400000;
            cfg.i2c_addr = 0x5D;          // при отказе библиотека сама пробует 0x14
            // Диапазон координат панели. Поворот учитывается ниже — сенсор и экран
            // должны смотреть в одну сторону, иначе нажатия попадают зеркально.
            cfg.x_min = 0; cfg.x_max = 239;
            cfg.y_min = 0; cfg.y_max = 319;
            cfg.bus_shared = false;       // сенсор на I2C, экран на SPI — не мешают
            cfg.offset_rotation = 0;
            _touch.config(cfg);
            _panel.setTouch(&_touch);
        }
        setPanel(&_panel);
    }
};

// ── шрифты ─────────────────────────────────────────────────────────────────────────────
//
// Встроенные шрифты библиотеки с КИРИЛЛИЦЕЙ. Прежняя библиотека её не имела вовсе, и
// русский текст выходил квадратиками — а мессенджер без русского бессмыслен.
//
// Названия с суффиксом JA — это не «японский шрифт». Семейство efont собрано из общей
// юникодной основы, и латиница с кириллицей и греческим в ней одинаковы у всех вариантов;
// различаются только иероглифические части. Отдельного русского варианта в библиотеке нет
// вовсе — я пробовал efontRU и получил ошибку сборки.
//
// Размеры под экран 320×240: мелкий для служебных строк, средний для текста, крупный для
// заголовков.
#define VUAL_FONT_SMALL  (&fonts::efontJA_10)
#define VUAL_FONT_TEXT   (&fonts::efontJA_14)
#define VUAL_FONT_TITLE  (&fonts::efontJA_16)

