// Ввод: клавиатура, трекбол и сенсорный экран.
//
// Три способа управления, и каждый хорош в своём:
//
//   · клавиатура — набор текста, ради неё устройство и куплено;
//   · трекбол — точное перемещение по списку, когда руки заняты и палец не поднять;
//   · касание — быстрые переходы: выбрать собеседника, вернуться, прокрутить ленту.
//
// Сенсор здесь не роскошь: на экране 320×240 попасть трекболом в нужную строку списка
// из десятка контактов заметно дольше, чем ткнуть пальцем.
#pragma once

#include <stdint.h>
#include <stddef.h>

namespace input {

// ── события ────────────────────────────────────────────────────────────────────────────

enum EventType : uint8_t {
    EV_NONE = 0,
    EV_CHAR,        // введён символ
    EV_BACKSPACE,
    EV_ENTER,
    EV_UP, EV_DOWN, EV_LEFT, EV_RIGHT,
    EV_SELECT,      // нажатие трекбола или касание элемента
    EV_BACK,        // возврат: жест справа налево
    EV_TAP,         // касание в точке
    EV_SWIPE_UP, EV_SWIPE_DOWN,
    EV_LONG_PRESS,  // удержание: рация — говорим, пока держим
    EV_RELEASE,     // отпустили после удержания
    EV_DRAG,        // палец тянет по вертикали; в y — смещение с прошлого события
};

struct Event {
    EventType type;
    char      ch;       // для EV_CHAR
    int16_t   x, y;     // для касаний
};

// ── клавиатура ─────────────────────────────────────────────────────────────────────────
//
// Клавиатура T-Deck висит на отдельном микроконтроллере и отдаёт по I2C уже готовый
// символ. Опрашивать её надо часто, но дёшево: чтение одного байта.
//
// Раскладка на клавишах латинская. Кириллица нужна обязательно — сообщения на русском
// иначе не набрать, — поэтому переключение раскладки повешено на удержание Alt.
namespace keyboard {

constexpr uint8_t kI2cAddr = 0x55;

enum Layout : uint8_t { LAYOUT_LATIN, LAYOUT_CYRILLIC };

/**
 * Состояние Shift.
 *
 * Своя механика поверх клавиатуры: одно нажатие поднимает регистр ОДНОЙ следующей буквы,
 * два быстрых — включают верхний регистр до следующего нажатия. Так набирают на любом
 * телефоне, и рука этого ждёт.
 */
enum ShiftMode : uint8_t { SHIFT_OFF, SHIFT_ONCE, SHIFT_CAPS };

void begin();
void setLayout(Layout l);
Layout layout();
ShiftMode shiftMode();

/** Нажатие клавиши Shift: выкл → один символ → (быстрое второе) верхний регистр → выкл. */
void shiftTap(uint32_t nowMs);

/** Буква введена — одноразовый Shift погашен. */
void shiftConsume();

/** Опросить клавиатуру. EV_NONE — ничего не нажато. */
Event poll();

/**
 * Кириллическая буква для латинской клавиши, в UTF-8.
 *
 * Раскладка привязана к МЕСТУ клавиши, а не к её обозначению: человек, знакомый с обычной
 * компьютерной клавиатурой, найдёт буквы там же, где привык — Q даёт Й, W даёт Ц и так
 * далее. Отдаём готовые байты, а не индекс: кириллица в UTF-8 занимает два байта, и
 * склеивать их на стороне вызывающего значило бы размазать раскладку по двум местам.
 *
 * Возвращает число записанных байт, 0 — для этой клавиши кириллицы нет.
 */
size_t cyrillicUtf8(char latin, char out[3]);

/**
 * Перебор: повторное нажатие той же клавиши в течение окна меняет ТОЛЬКО ЧТО введённую
 * букву на следующую из цепочки. Так добираются буквы, которым не хватило клавиш:
 * Е→Ё, У→Ю, И→Б, З→Х, Д→Ж→Э, Ь→Ъ. Цепочки подобраны по соседству на обычной
 * клавиатуре и по созвучию — чтобы рука находила их без шпаргалки.
 *
 * latin — латинская клавиша (регистр не важен), upper — поднят ли регистр. В out —
 * байты буквы; replacePrev на выходе — надо ли стереть предыдущую букву (это не первое
 * нажатие цепочки). Возвращает число байт; 0 — клавиша вне цепочек, и на неё отвечает
 * обычная раскладка.
 */
size_t multiTap(char latin, bool upper, uint32_t nowMs, char out[3], bool& replacePrev);

/** Сбросить перебор — любой другой ввод обрывает цепочку. */
void multiTapReset();

}  // namespace keyboard

// ── трекбол ────────────────────────────────────────────────────────────────────────────
//
// Четыре вывода направления плюс нажатие. Импульсы приходят часто, поэтому события
// прореживаются: без этого одно движение пальца прокручивает список до конца.
namespace trackball {

void begin();
Event poll();

/** Сколько импульсов считать одним шагом. Подобрано так, чтобы список шёл предсказуемо. */
constexpr uint8_t kStepPulses = 3;

}  // namespace trackball

// ── сенсорный экран ────────────────────────────────────────────────────────────────────
//
// Контроллер GT911. Распознаём касание, удержание и смахивание — этого достаточно для
// навигации, а сложные жесты на таком экране только мешают.
namespace touch {

constexpr uint8_t kI2cAddrPrimary = 0x5D;
constexpr uint8_t kI2cAddrAlt     = 0x14;   // адрес зависит от разводки сброса

bool begin();
Event poll();

/** Порог смахивания в точках. Меньше — случайные касания превращаются в жесты. */
constexpr int16_t kSwipeMin = 48;
/** Дольше этого — удержание, а не касание. */
constexpr uint32_t kLongPressMs = 450;
/** С этого смещения по вертикали начинается живое перетаскивание. Меньше порога
 *  смахивания: перетаскивание должно подхватывать ленту раньше, чем жест «дозреет»
 *  до смахивания, — иначе лента стоит, пока палец уже едет. */
constexpr int16_t kDragStart = 14;

}  // namespace touch

// ── распознавание жеста ────────────────────────────────────────────────────────────────
//
// Вынесено отдельно от чтения контроллера: логика жестов не зависит от железа, а значит
// проверяется тестами до заливки. Ошибка здесь особенно неприятна — устройство начинает
// «жить своей жизнью», и причина неочевидна.

struct GestureState {
    bool     down = false;
    int16_t  x0 = 0, y0 = 0;
    uint32_t t0 = 0;
    bool     longFired = false;
    bool     dragging = false;   // палец тянет ленту: события идут по ходу движения
    int16_t  lastY = 0;          // откуда считать следующее смещение
};

/**
 * Скормить состояние касания и получить событие.
 * pressed — палец на экране прямо сейчас; x, y — его положение; nowMs — время.
 */
Event feedGesture(GestureState& st, bool pressed, int16_t x, int16_t y, uint32_t nowMs);

}  // namespace input
