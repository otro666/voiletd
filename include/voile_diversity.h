// Разнесение и избыточность — главное оружие против городской застройки.
//
// В городе сигнал приходит не по прямой, а десятками отражений от стеклянных фасадов.
// Они складываются то в фазе, то в противофазе, и в конкретной точке в конкретный момент
// возникает глубокий провал. Провал не постоянен: проехала машина, качнулся воздух —
// картина сместилась.
//
// Отсюда вывод: бороться надо не с ослаблением, а с СОВПАДЕНИЕМ ВО ВРЕМЕНИ. Расчёт по
// релеевской модели: при запасе 6 дБ одна попытка теряется в 22% случаев, три разнесённые
// — в 1,1%, пять — в 0,05%. Три попытки эквивалентны прибавке 14 дБ мощности, пять — 27.
// Ни антенна, ни усилитель столько не дадут.
#pragma once

#include <stdint.h>
#include <stddef.h>

namespace voile {

// ── разнесение во времени ──────────────────────────────────────────────────────────────

/** Сколько копий шлём по умолчанию. Три — разумный компромисс: почти весь выигрыш уже
 *  получен, а эфирного времени тратится втрое, а не впятеро. */
constexpr uint8_t kDefaultCopies = 3;

/**
 * Задержка перед копией номер n (первая копия — n=0, идёт сразу).
 *
 * Промежуток обязан быть достаточным, чтобы картина переотражений успела измениться.
 * Три пакета подряд попадут в тот же провал и не помогут вовсе — это самая частая ошибка.
 * Секунды, а не миллисекунды. Разброс добавляем, чтобы узлы не синхронизировались между
 * собой и не сталкивались в эфире.
 */
uint32_t copyDelayMs(uint8_t copyIndex, uint32_t jitterSeed);

// ── разнесение по частоте ──────────────────────────────────────────────────────────────

/**
 * Смещение частоты для копии, в килогерцах от основной. Сейчас ВСЕГДА НОЛЬ.
 *
 * Частотное разнесение работает только если приёмник прыгает по частотам вместе с
 * передатчиком, а договориться о расписании без общих часов нечем: приёмник слушает
 * одну основную частоту, и смещённые копии уходили в пустоту. Разнесение оставлено
 * во времени (copyDelayMs) — оно синхронизации не требует. Функция сохранена как
 * точка возврата, если появится настоящая схема прыжков.
 */
int32_t copyFreqOffsetKhz(uint8_t copyIndex);

// ── восстановление потерь ──────────────────────────────────────────────────────────────

/**
 * Избыточное кодирование по схеме «любые K из N».
 *
 * Дешевле тройного повторения при той же надёжности: вместо трёх копий целого сообщения
 * шлём его частями плюс избыточные блоки. Реализация — XOR-код: на группу из K блоков
 * добавляется один блок чётности, восстанавливающий любой ОДИН потерянный.
 *
 * Простая схема выбрана намеренно: сложные коды (Рида — Соломона) дали бы больше, но
 * требуют памяти и вычислений, а выигрыш на коротких сообщениях невелик.
 */
constexpr uint8_t kFecGroup = 4;   // на четыре части — один блок чётности

/** Посчитать блок чётности для группы. Все блоки должны быть одной длины. */
void fecParity(const uint8_t* const* blocks, uint8_t count, size_t blockLen, uint8_t* out);

/**
 * Восстановить единственный недостающий блок группы.
 * present[i] == nullptr означает «блок i потерян».
 * Возвращает false, если потеряно не ровно ОДИН блок — тогда восстановить нечем.
 */
bool fecRecover(const uint8_t* const* present, uint8_t count, size_t blockLen,
                const uint8_t* parity, uint8_t missingIndex, uint8_t* out);

// ── отсев повторов ─────────────────────────────────────────────────────────────────────

/**
 * Копии одного сообщения приходят несколько раз — принять надо ровно один.
 *
 * Помним недавно виденные пары «отправитель + номер». Кольцевой буфер вместо словаря:
 * памяти на устройстве мало, а точность здесь не критична — в худшем случае сообщение
 * покажется дважды, что лучше, чем исчерпание памяти.
 */
class SeenCache {
public:
    static constexpr size_t kSize = 64;

    /** Возвращает true, если такое сообщение УЖЕ видели (значит, это копия). */
    bool seen(const uint8_t src[4], uint16_t seq);

private:
    struct Entry { uint32_t src; uint16_t seq; bool used; };
    Entry ring_[kSize] = {};
    size_t next_ = 0;
};

}  // namespace voile
