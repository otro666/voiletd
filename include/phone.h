// Связь с ТЕЛЕФОННОЙ версией Vual через локальную сеть.
//
// Почему это отдельный модуль, а не часть net.cpp. Знакомство с телефоном уже работало:
// плата и телефон видят анонсы друг друга в группе 239.255.77.77 и обмениваются
// PING/PONG — отсюда и «собеседник найден в эфире». Но дальше телефон разговаривает
// СВОИМ языком, которого у платы не было вовсе:
//
//   1. визитка (Card) — JSON с личностью P-256, эфемерным ключом и подписью ECDSA;
//   2. встреча — визитки кладутся в «комнату» SHA-1("vual1-d:"+фраза) как значения DHT;
//   3. линк — кадры [тип 1][номер 8][AES-256-GCM], поверх обфускация VoileCloak;
//   4. текст — первый байт 1, дальше UTF-8.
//
// Здесь ровно эти четыре вещи и портированы, по исходникам телефонной версии
// (VoileCrypto.kt, DhtRail.kt, VoileLink.kt, VoileSession.kt). Никаких «своих» форматов:
// любое отклонение означало бы, что телефон нас не понимает, а отладить это на плате
// без монитора почти невозможно.
//
// Чего здесь НЕТ и почему: храповик (Double Ratchet) и прикрывающий трафик. Телефон
// понимает и кадры без них — он смотрит на метку первого байта (0xD0 храповик,
// 0xC0/0xC1 прикрытие) и обычный кадр принимает как есть. Плате эти слои стоили бы
// памяти и времени, которых у неё нет.
#pragma once

#include <stdint.h>
#include <stddef.h>

namespace phone {

/** Готов ли модуль (есть личность и сеть). */
bool begin();

/**
 * Задать общую фразу знакомства. Из неё выводится комната встречи — та же формула,
 * что в телефонной версии (Rooms.infoHash), иначе стороны не встретятся.
 */
void setPhrase(const char* phrase);

/** Идёт ли обмен с телефоном (линк поднят). */
bool linked();

/** Имя/отпечаток собеседника, когда визитка проверена; пустая строка — пока нет. */
const char* peerName();

/**
 * Отправить текст телефону. false — линк не поднят.
 * Кадр: [1][UTF-8], как в VoileSession.frame(isText = true).
 */
bool sendText(const char* text);

/** Обработчик принятого текста. */
void setOnText(void (*cb)(const char* from, const char* text));

/**
 * Кадр знакомства пришёл с рельсы (брокер или Nostr).
 *
 * Рельсы дека принимают сообщения своих комнат; те, что относятся к комнате «набора»,
 * отдаются сюда — разбор у них общий с локальным путём DHT.
 */
void onRailWire(const char* roomHex, const char* json);

/** Комната «набора» в шестнадцатеричном виде — на неё подписываются рельсы. */
void roomHexOut(char out[41]);

/**
 * Кадр знакомства, уже разобранный рельсой: вид ('o' или 'a'), к какому предложению
 * относится и визитка. Рельсы дека отдают сообщения именно так, и собирать из них
 * обратно JSON только ради разбора было бы глупо.
 */
void onRailIncoming(char kind, const uint8_t offerId[20], const char* cardJson);

/** Обслуживание: встреча, поддержание линка, приём. Вызывать из главного цикла. */
void pump();

}  // namespace phone
