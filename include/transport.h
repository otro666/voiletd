// Два транспорта одновременно.
//
// Собеседники бывают двух видов, и это не режимы устройства, а свойство контакта:
//
//   · телефоны с Вуалью — через Wi-Fi, полный протокол Voile, всё как на телефоне:
//     текст, файлы, фотографии, стикеры, голосовые, рация;
//   · соседние T-Deck — по радио, сжатый профиль, только текст и короткие голосовые.
//
// Оба работают ОДНОВРЕМЕННО: Wi-Fi и SX1262 сидят на разных выводах и не мешают друг
// другу. Единственное, за чем нужно следить, — питание: при передаче на полной мощности
// вместе с активным Wi-Fi просадка заметна, поэтому передача разведена по времени.
#pragma once

#include <stdint.h>
#include <stddef.h>

namespace transport {

enum Rail : uint8_t {
    RAIL_NONE = 0,
    RAIL_WIFI = 1,     // полный протокол, совместим с телефоном
    RAIL_LORA = 2,     // сжатый профиль
};

/** Что умеет рельса — от этого зависит, какие виды сообщений вообще предлагать. */
struct Caps {
    bool text;
    bool files;        // фотографии, стикеры, документы
    bool voiceMsg;     // голосовое сообщение файлом
    bool ptt;          // рация: непрерывный поток
    uint32_t bps;      // пропускная способность, бит/с
};

constexpr Caps kWifiCaps = { true,  true,  true,  true,  1000000 };
// По радио файлы формально возможны, но фотография в 200 КБ при 300 бит/с — это полтора
// часа эфира, что и невежливо, и запрещено лимитом. Поэтому честно отключено.
constexpr Caps kLoraCaps = { true,  false, true,  false, 1758 };

constexpr Caps capsOf(Rail r) {
    return r == RAIL_WIFI ? kWifiCaps : kLoraCaps;
}

// ── маршрутизация ──────────────────────────────────────────────────────────────────────

/** Что известно про собеседника. */
struct PeerRoute {
    uint8_t addr[4];
    bool    wifiSeen;      // отвечал по Wi-Fi
    bool    loraSeen;      // слышен по радио
    uint32_t wifiLastMs;
    uint32_t loraLastMs;
};

/**
 * Выбрать путь для сообщения.
 *
 * Wi-Fi предпочтительнее всегда, когда он есть: быстрее, без лимита эфирного времени и
 * с полным набором возможностей. Радио — запасной путь, который работает, когда сети нет
 * вовсе, и ради которого устройство и покупают.
 *
 * Свежесть важна: собеседник мог уйти из сети минуту назад, и слать ему по Wi-Fi
 * бессмысленно. Порог намеренно щедрый — переключаться туда-сюда хуже, чем подождать.
 */
Rail pickRail(const PeerRoute& p, uint32_t nowMs, bool needFiles);

constexpr uint32_t kWifiStaleMs = 90000;    // полторы минуты без ответа — считаем ушедшим
constexpr uint32_t kLoraStaleMs = 600000;   // радио редкое по природе, порог больше

// ── разбиение на части ─────────────────────────────────────────────────────────────────

/**
 * Файл разбивается на части по-разному для двух рельс, и разница огромна: по Wi-Fi
 * кусок 45 КБ, по радио — 200 байт. Общий код разбиения избавляет от двух реализаций,
 * которые неминуемо разъехались бы.
 */
size_t chunkSize(Rail r);

/** Сколько частей выйдет и влезет ли это в разумное время. */
struct Estimate {
    uint32_t parts;
    uint32_t seconds;      // ожидаемое время передачи
    bool     sane;         // стоит ли вообще браться
};

Estimate estimate(Rail r, size_t bytes);

}  // namespace transport
