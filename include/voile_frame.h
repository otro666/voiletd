// Формат кадра Voile для LoRa.
//
// Отдельный профиль, не тот, что по Wi-Fi. Причина проста: заголовок храповика в
// телефонной версии весит 136 байт (JSON плюс ключ P-256 в base64), сегмент надёжной
// доставки ещё 8, прикрытие 5, тег и маскировка около 32. Итого около 181 байта
// накладных при пределе пакета LoRa в 255 — на текст осталось бы 74 байта.
//
// Здесь всё двоичное и плотное:
//   обычный кадр            13 байт  → на текст 242
//   кадр со сменой ключа    46 байт  (сжатая точка кривой, 33 байта вместо 88)
//
// Прикрытия нет намеренно: при лимите эфирного времени пустышки непозволительны.
#pragma once

#include <stdint.h>
#include <stddef.h>

namespace voile {

// ── размеры ────────────────────────────────────────────────────────────────────────────
constexpr size_t kMaxPacket   = 255;   // предел полезной нагрузки LoRa
constexpr size_t kTagLen      = 8;     // укороченный тег AEAD: при таких объёмах и
                                       // скорости перебора 64 бит достаточно, а 8 байт
                                       // на каждом сообщении — заметная экономия
constexpr size_t kPubLen      = 33;    // точка P-256 в сжатом виде
constexpr size_t kAddrLen     = 4;     // укороченный адрес узла (от отпечатка ключа)

// ── типы кадров ────────────────────────────────────────────────────────────────────────
enum FrameType : uint8_t {
    FT_MSG      = 0x01,   // сообщение
    FT_MSG_KEY  = 0x02,   // сообщение + новый ключ храповика (смена цепочки)
    FT_ACK      = 0x03,   // подтверждение
    FT_HELLO    = 0x04,   // объявление о себе (знакомство, поддержание таблицы соседей)
    FT_RELAY    = 0x05,   // ретрансляция чужого кадра
    FT_PARITY   = 0x06,   // избыточный блок для восстановления потерянных
};

// ── заголовок ──────────────────────────────────────────────────────────────────────────
//
// Поля упакованы вручную, без выравнивания: каждый байт в эфире стоит времени.
//
//   0       тип
//   1..4    адрес получателя (усечённый отпечаток)
//   5..8    адрес отправителя
//   9..10   номер сообщения (16 бит, циклический)
//   11      номер части | всего частей  (по 4 бита) — для длинных сообщений
//   12      номер копии | всего копий   (по 4 бита) — разнесение во времени
//
// Дальше: при FT_MSG_KEY — 33 байта ключа. Затем шифртекст и тег.
constexpr size_t kHdrLen = 13;

struct Header {
    uint8_t  type;
    uint8_t  dst[kAddrLen];
    uint8_t  src[kAddrLen];
    uint16_t seq;
    uint8_t  part;      // старшие 4 бита — номер, младшие — всего
    uint8_t  copy;      // старшие 4 бита — номер копии, младшие — всего копий
};

/** Записать заголовок в буфер. Возвращает число записанных байт. */
size_t writeHeader(uint8_t* out, const Header& h);

/** Разобрать заголовок. Возвращает false, если данных не хватает. */
bool readHeader(const uint8_t* in, size_t len, Header& h);

inline uint8_t partIndex(uint8_t p) { return uint8_t(p >> 4); }
inline uint8_t partTotal(uint8_t p) { return uint8_t(p & 0x0F); }
inline uint8_t packPart(uint8_t idx, uint8_t total) {
    return uint8_t((idx << 4) | (total & 0x0F));
}

/** Сколько полезных данных влезает в один кадр данного типа. */
constexpr size_t payloadCapacity(bool withKey) {
    return kMaxPacket - kHdrLen - (withKey ? kPubLen : 0) - kTagLen;
}

}  // namespace voile
