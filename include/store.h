// Хранилище на microSD.
//
// Карта решает главное ограничение платы: во внутренней памяти держать переписку,
// фотографии и голосовые негде — там сотни килобайт, а не гигабайты.
//
// Формат намеренно простой: журнал с дописыванием в конец вместо базы данных. Причина в
// том, что питание на таком устройстве пропадает без предупреждения — сел аккумулятор,
// нажали сброс, — и база с индексами в этот момент рискует остаться в несогласованном
// виде. Журнал же всегда читается до последней целой записи, а хвост просто отбрасывается.
#pragma once

#include <stdint.h>
#include <stddef.h>

namespace store {

// ── раскладка на карте ─────────────────────────────────────────────────────────────────
//
//   /vual/chats/<адрес>.log     переписка: журнал записей
//   /vual/files/<идентификатор> принятые и отправленные файлы
//   /vual/thumbs/<идентификатор>.jpg  обложки фотографий и кружков
//   /vual/outbox.log            очередь на отправку — переживает выключение
//   /vual/keys/<адрес>          состояние храповика по каждому собеседнику

constexpr const char* kRoot = "/vual";

// ── запись журнала ─────────────────────────────────────────────────────────────────────
//
// Каждая запись самодостаточна: длина, контрольная сумма, затем содержимое. Обрыв питания
// посреди записи означает лишь то, что последняя запись не сойдётся по сумме и будет
// отброшена при чтении — остальное цело.

enum RecKind : uint8_t {
    REC_TEXT    = 1,
    REC_VOICE   = 2,    // голосовое: ссылка на файл + длительность
    REC_PHOTO   = 3,
    REC_STICKER = 4,
    REC_SYSTEM  = 5,
};

struct RecHeader {
    uint16_t len;        // длина содержимого
    uint16_t crc;        // контрольная сумма содержимого
    uint8_t  kind;
    uint8_t  flags;      // бит 0 — наше, бит 1 — доставлено, бит 2 — прочитано
    uint32_t ts;         // время, секунды
    uint16_t seq;
};

constexpr size_t kRecHdrLen = 12;
constexpr uint8_t kFlagMine      = 1 << 0;
constexpr uint8_t kFlagDelivered = 1 << 1;
constexpr uint8_t kFlagRead      = 1 << 2;

size_t writeRecHeader(uint8_t* out, const RecHeader& h);
bool   readRecHeader(const uint8_t* in, size_t len, RecHeader& h);

/** Контрольная сумма записи. CRC-16, а не что-то тяжелее: задача — поймать обрыв записи
 *  и порчу сектора, а не защититься от подделки. Целостность обеспечивает шифрование. */
uint16_t crc16(const uint8_t* data, size_t len);

/** Проверить запись целиком: сходится ли длина и сумма. */
bool recordValid(const uint8_t* rec, size_t available, size_t& consumed);

// ── очередь отправки ───────────────────────────────────────────────────────────────────
//
// Лежит на карте, а не в памяти: сообщение, написанное вне зоны действия, должно уйти
// после включения через сутки, а не пропасть при разряде батареи.

struct OutboxEntry {
    uint8_t  dst[4];
    uint16_t seq;
    uint8_t  kind;
    uint8_t  rail;       // предпочтительный путь, 0 — любой
    uint32_t createdAt;
    uint32_t fileOffset; // докачка с прерванного места
};

}  // namespace store
